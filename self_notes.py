def auto_generate_note(
    interactions: list[dict] | None = None,
    patterns: list[dict] | None = None,
    tips: list[dict] | None = None,
) -> list[str]:
    """Analyze session data and auto-create notes.

    Returns a list of created note IDs.
    """
    created: list[str] = []

    if patterns:
        # Generate a note for significant patterns
        top_patterns = sorted(patterns, key=lambda p: -p.get("count", 0))[:3]
        for p in top_patterns:
            ptype = p.get("type", "unknown")
            count = p.get("count", 0)
            if count < 3:
                continue

            if ptype == "frequent_tool":
                tool = p.get("tool", "unknown")
                title = f"Frequent tool: {tool}"
                content = (
                    f"The `{tool}` tool has been used {count} times in this session. "
                    f"Consider whether this pattern indicates a recurring workflow "
                    f"that could be automated or turned into a reusable skill."
                )
                note_id = create_note(
                    title=title,
                    content=content,
                    note_type="pattern",
                    tags=["auto", "tool", tool],
                    auto_generated=True,
                )
                created.append(note_id)

            elif ptype == "topic":
                kw = p.get("keyword", "topic")
                title = f"Frequent topic: {kw}"
                content = (
                    f"The topic \"{kw}\" appeared {count} times in this session. "
                    f"The user seems to have a recurring interest in this area. "
                    f"Consider keeping relevant context ready for future sessions."
                )
                note_id = create_note(
                    title=title,
                    content=content,
                    note_type="pattern",
                    tags=["auto", "topic", kw],
                    auto_generated=True,
                )
                created.append(note_id)

            elif ptype == "repetition":
                kws = ", ".join(p.get("keywords", [])[:3])
                title = f"Repeated pattern: {kws}"
                content = (
                    f"A repeated request pattern was detected {count} times: {kws}. "
                    f"This suggests the user has a recurring task that could benefit "
                    f"from a reusable skill or saved workflow."
                )
                note_id = create_note(
                    title=title,
                    content=content,
                    note_type="pattern",
                    tags=["auto", "repetition"],
                    auto_generated=True,
                )
                created.append(note_id)

    if tips:
        active_tips = [t for t in tips if not t.get("applied", False)]
        if active_tips:
            title = "Self-improvement tips available"
            content = (
                f"The self-improvement system has {len(active_tips)} active tip(s):\n\n"
            )
            for t in active_tips[:5]:
                content += f"- {t.get('message', '')}\n"
            content += "\nReview these tips to improve agent behaviour."
            note_id = create_note(
                title=title,
                content=content,
                note_type="tip",
                tags=["auto", "tips"],
                auto_generated=True,
            )
            created.append(note_id)

    return created


